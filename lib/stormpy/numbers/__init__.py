"""Number types of Storm.

The Python types matching the value types used by Storm in C++:

- ``float``: ``double``
- :class:`Rational`: ``storm::RationalNumber`` (exact arithmetic)
- :class:`Integer`: integer type of ``storm::RationalNumber`` (arbitrary precision)
- :class:`RationalFunction`: ``storm::RationalFunction`` (parametric models), with coefficients of type
  :class:`RationalFunctionCoefficient` and the (factorized) :class:`Polynomial` or the non-factorized :class:`RawPolynomial`
- :class:`Interval`: ``storm::Interval`` (interval models)
- :class:`RationalInterval`: ``storm::RationalInterval`` (exact interval models)

The value types are also available directly in :mod:`stormpy`, e.g. ``stormpy.Rational`` is ``stormpy.numbers.Rational``.
They select template instantiations, e.g. ``stormpy.build_model[stormpy.Rational](program)``.

Parameters of parametric models are represented by :class:`Variable` objects.

The complete bindings of the carl library (e.g. polynomials, constraints, formulas and parsing) are available in
:mod:`stormpy.numbers.developer`, which is only meant for developers.
"""

